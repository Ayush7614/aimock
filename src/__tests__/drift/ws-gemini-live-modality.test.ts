// The three-way comparison, run locally end to end
// ---------------------------------------------------------------------------
//
// The live drift leg's own three-way grading only executes with a real
// GOOGLE_API_KEY. This runs the SAME grading — the same sdk shapes, the same
// `compareSSESequences`, the same aimock WS handler over the same drift-server
// fixtures — with the fake provider standing in for Google, so the MOCK side of
// the leg is verified here instead of first being exercised in CI against a live
// endpoint. It proves aimock reproduces the AUDIO turn's shape; it does NOT
// prove Google emits that shape (only a live run can).

describe("three-way AUDIO comparison: sdk shapes × provider turn × aimock", () => {
  let instance: ServerInstance;

  beforeAll(async () => {
    instance = await startDriftServer();
  });

  afterAll(async () => {
    await stopDriftServer(instance);
  });

  /** Drive aimock exactly as the drift leg's mock side does. */
  async function driveMock(): Promise<unknown[]> {
    const mockWs = await connectWebSocket(instance.url, GEMINI_WS_PATH);
    mockWs.send(
      JSON.stringify({
        setup: {
          model: OBSERVED_MODEL,
          generationConfig: { responseModalities: GEMINI_LIVE_RESPONSE_MODALITIES },
        },
      }),
    );
    const setupMsgs = await mockWs.waitForMessages(1);
    const raw: unknown[] = [JSON.parse(setupMsgs[0])];
    mockWs.send(
      JSON.stringify({
        clientContent: {
          turns: [{ role: "user", parts: [{ text: AUDIO_PROMPT }] }],
          turnComplete: true,
        },
      }),
    );
    const content = await collectMockWSMessages(
      mockWs,
      (msg) => (msg as LiveServerMessage | null)?.serverContent?.turnComplete === true,
      15000,
      1,
    );
    raw.push(...content.rawMessages);
    mockWs.close();
    return raw;
  }

  it("aimock streams an AUDIO turn for the drift server's audio fixture", async () => {
    const turn = summarizeGeminiLiveTurn(await driveMock());
    expect(turn.setupCompleteCount).toBe(1);
    expect(turn.audioPartCount).toBeGreaterThan(0);
    expect(turn.turnCompleteCount).toBeGreaterThan(0);
    expect(turn.textPartCount).toBe(0);
  });

  it("reports NO critical drift between the sdk audio shape, the provider turn, and aimock", async () => {
    const realResult = await withProvider({}, (provider) => probe(provider));
    const mockRaw = await driveMock();
    const mockEvents = mockRaw.map((msg) => ({
      type: classifyGeminiMessage(msg as Record<string, unknown>),
      dataShape: extractShape(msg),
    }));

    const diffs = compareSSESequences(
      [geminiLiveSetupCompleteShape(), ...geminiLiveAudioEventShapes()],
      realResult.events,
      mockEvents,
    );

    expect(diffs.filter((d) => d.severity === "critical")).toEqual([]);
  });

  it("GUARD: a mock missing the audio payload IS reported as critical drift", async () => {
    // Non-vacuity of the test above. If the mock's serverContent lost its
    // inlineData, the comparison must go critical — otherwise "no critical
    // drift" means nothing. The mock side here is a text turn (aimock's TEXT
    // shape) graded against the provider's AUDIO turn.
    const realResult = await withProvider({}, (provider) => probe(provider));
    const textShapedMock = [
      { type: "setupComplete", dataShape: extractShape({ setupComplete: {} }) },
      {
        type: "serverContent",
        dataShape: extractShape({
          serverContent: { modelTurn: { parts: [{ text: "Hello!" }] }, turnComplete: true },
        }),
      },
    ];

    const diffs = compareSSESequences(
      [geminiLiveSetupCompleteShape(), ...geminiLiveAudioEventShapes()],
      realResult.events,
      textShapedMock,
    );

    const critical = diffs.filter((d) => d.severity === "critical");
    expect(critical.length).toBeGreaterThan(0);
    expect(critical.map((d) => d.path).join(" ")).toContain("inlineData");
  });
});

// ---------------------------------------------------------------------------
// The TOOL turn, run locally end to end
// ---------------------------------------------------------------------------
//
// Run 31896605497's head drift report carried exactly one Gemini Live diff, on
// the TOOL-CALL leg (the audio leg graded clean):
//
//   severity: critical
//   path:     SSE:serverContent
//   issue:    real API emits event type "serverContent" but mock does not
//   real:     serverContent
//   mock:     <absent>
//
// The provider was NOT emitting an event aimock has never heard of — aimock
// emits `serverContent` in every other branch of the Live handler. What it
// could not do was emit one in a TOOL turn, for two compounding reasons:
//
//   1. the leg drove the mock with the shared, text-shaped TOOL_FIXTURE, whose
//      Live rendering is a bare `toolCall` with no model turn at all; and
//   2. the ONE fixture shape that expresses "the model speaks AND calls a
//      function" — an AudioResponse carrying the `toolCalls` companion — was
//      silently dropping that companion in the Live handler's audio branch.
//
// So (2) made the correct drive (1) inexpressible. Both are fixed, and the
// three tests below hold each end of that down: the mis-drive still reproduces
// the reported critical, the corrected drive grades clean, and a mock that
// loses the model turn still goes critical.
describe("three-way TOOL comparison: sdk shapes × provider turn × aimock", () => {
  let liveInstance: ServerInstance;
  let sharedInstance: ServerInstance;

  beforeAll(async () => {
    liveInstance = await startGeminiLiveDriftServer();
    sharedInstance = await startDriftServer();
  });

  afterAll(async () => {
    await stopDriftServer(liveInstance);
    await stopDriftServer(sharedInstance);
  });

  /**
   * Drive aimock exactly as the tool-call drift leg's mock side does, against
   * whichever fixture set is under test.
   */
  async function driveMockTool(instance: ServerInstance): Promise<unknown[]> {
    const mockWs = await connectWebSocket(instance.url, GEMINI_WS_PATH);
    mockWs.send(
      JSON.stringify({
        setup: {
          model: OBSERVED_MODEL,
          tools: WEATHER_TOOLS,
          generationConfig: { responseModalities: GEMINI_LIVE_RESPONSE_MODALITIES },
        },
      }),
    );
    const setupMsgs = await mockWs.waitForMessages(1);
    const raw: unknown[] = [JSON.parse(setupMsgs[0])];
    mockWs.send(
      JSON.stringify({
        clientContent: {
          turns: [{ role: "user", parts: [{ text: TOOL_PROMPT }] }],
          turnComplete: true,
        },
      }),
    );
    // A short budget on purpose: a mock that never emits the `toolCall` must
    // fail as the collector's own "timed out … Collected N messages" — which
    // names the defect — rather than as vitest's bare per-test timeout, which
    // names nothing. Everything here is local and answers in milliseconds.
    const content = await collectMockWSMessages(
      mockWs,
      (msg) => !!msg && typeof msg === "object" && "toolCall" in msg,
      3000,
      1,
    );
    raw.push(...content.rawMessages);
    mockWs.close();
    return raw;
  }

  function toEvents(raw: unknown[]) {
    return raw.map((msg) => ({
      type: classifyGeminiMessage(msg as Record<string, unknown>),
      dataShape: extractShape(msg),
    }));
  }

  const toolSdkShapes = () => [geminiLiveSetupCompleteShape(), ...geminiLiveToolCallEventShapes()];

  it("REPRODUCTION: the text-shaped tool fixture still reports SSE:serverContent as <absent>", async () => {
    // The mis-drive, kept alive on purpose. This is the reported failure, not a
    // paraphrase of it: the shared TOOL_FIXTURE renders as a bare `toolCall`,
    // and grading that against a provider turn that speaks first produces the
    // artifact's diff verbatim. If a future change made this pass, the leg
    // would have stopped being able to see the bug it was built for.
    const realResult = await withProvider({}, (provider) =>
      probe(provider, WEATHER_TOOLS, undefined, TOOL_PROMPT),
    );
    const mockRaw = await driveMockTool(sharedInstance);

    // The mock's own turn: a tool call and nothing before it.
    expect(summarizeGeminiLiveTurn(mockRaw)).toMatchObject({
      toolCallCount: 1,
      audioPartCount: 0,
      textPartCount: 0,
    });

    const diffs = compareSSESequences(toolSdkShapes(), realResult.events, toEvents(mockRaw));
    expect(diffs).toContainEqual(
      expect.objectContaining({
        path: "SSE:serverContent",
        severity: "critical",
        expected: "serverContent",
        real: "serverContent",
        mock: "<absent>",
      }),
    );
  });

  it("aimock streams the model turn BEFORE the tool call for the Live tool fixture", async () => {
    const raw = await driveMockTool(liveInstance);

    // Ordering is the whole point, so it is asserted on the SEQUENCE, not on
    // counts: counts alone would pass a mock that spoke after calling, which is
    // what the handler used to do (its `turnComplete` trailed the `toolCall`
    // and the probe therefore never saw it).
    expect(toEvents(raw).map((e) => e.type)).toEqual([
      "setupComplete",
      "serverContent",
      "toolCall",
    ]);

    const turn = summarizeGeminiLiveTurn(raw);
    expect(turn.setupCompleteCount).toBe(1);
    expect(turn.audioPartCount).toBeGreaterThan(0);
    expect(turn.toolCallCount).toBe(1);
    // AUDIO modality: the turn speaks, it does not write.
    expect(turn.textPartCount).toBe(0);
  });

  it("reports NO critical drift between the sdk tool shapes, the provider turn, and aimock", async () => {
    const realResult = await withProvider({}, (provider) =>
      probe(provider, WEATHER_TOOLS, undefined, TOOL_PROMPT),
    );
    const mockRaw = await driveMockTool(liveInstance);

    const diffs = compareSSESequences(toolSdkShapes(), realResult.events, toEvents(mockRaw));

    expect(diffs.filter((d) => d.severity === "critical")).toEqual([]);
  });

  it("GUARD: a mock whose model turn lost its audio IS reported as critical drift", async () => {
    // Non-vacuity of the test above. The mock side here keeps the correct EVENT
    // SEQUENCE — serverContent then toolCall — and only empties the model turn,
    // so a comparison that graded event types alone would call this clean.
    const realResult = await withProvider({}, (provider) =>
      probe(provider, WEATHER_TOOLS, undefined, TOOL_PROMPT),
    );
    const hollowMock = [
      { type: "setupComplete", dataShape: extractShape({ setupComplete: {} }) },
      {
        type: "serverContent",
        dataShape: extractShape({ serverContent: { modelTurn: { parts: [{ text: "" }] } } }),
      },
      {
        type: "toolCall",
        dataShape: extractShape({
          toolCall: { functionCalls: [{ name: "get_weather", args: {}, id: "x" }] },
        }),
      },
    ];

    const diffs = compareSSESequences(toolSdkShapes(), realResult.events, hollowMock);

    const critical = diffs.filter((d) => d.severity === "critical");
    expect(critical.length).toBeGreaterThan(0);
    expect(critical.map((d) => d.path).join(" ")).toContain("inlineData");
  });
});

// ---------------------------------------------------------------------------
// The MIRROR-IMAGE refusal: a bidiGenerateContent model that refuses AUDIO
//
// THE BUG. Everything above rests on a premise this file used to state as fact:
// "every model exposing `bidiGenerateContent` is a native-audio model that
// supports only `AUDIO`". Google falsified it on 2026-08-26 by shipping
// `gemini-3.5-transcribe-live` — a streaming SPEECH-TO-TEXT model that declares
// `bidiGenerateContent` and emits only TEXT. The live leg's discovery filters
// on that declared method alone (correctly: the model NAME carries no
// capability signal), so the listing handed it to the probe, the probe asked
// for AUDIO, and the provider refused with the mirror image of the frame at the
// top of this file, recovered verbatim from the drift-report artifact of run
// 33296393200:
//
//   code=1007 reason="The requested combination of response modalities (AUDIO)
//   is not supported by the model. models/gemini-3.5-transcribe-live"
//
// The whole Gemini Live leg went red on that refusal every run from 2026-08-27.
//
// THE FIX is not a name filter and not a hardcoded pin — both are the mistakes
// this leg has already made. Response modality is a per-model capability the
// `/models` listing does not express, so the ONLY authority on it is the
// provider, and `driveGeminiLiveAudio` asks: it walks the listing's candidates
// in order and a 1007 modality refusal disqualifies that candidate and advances
// to the next.
//
// THE PROOF, against the same local TLS server, with the per-model rule enforced
// by the "provider" rather than by these expectations:
//
//   RED   — driving candidate[0] directly (the pre-fix behaviour) fails with
//           exactly the 1007 frame above.
//   GREEN — `driveGeminiLiveAudio` over the same ordered candidates reports that
//           refusal, advances, and completes a real AUDIO turn on candidate[1].
// ---------------------------------------------------------------------------

/** The streaming transcriber the live listing now hands the probe first. */
const TRANSCRIBE_LIVE_MODEL = "models/gemini-3.5-transcribe-live";

/** A native-audio model, later in the same listing — the one that serves AUDIO. */
const NATIVE_AUDIO_MODEL = "models/gemini-2.5-flash-native-audio-latest";

/**
 * The CLOSE reason Google sent, copied verbatim from the `drift-report`
 * artifact of run 33296393200 rather than generated by this file's
 * expectations.
 */
const OBSERVED_AUDIO_1007_REASON =
  "The requested combination of response modalities (AUDIO) is not supported by the model. " +
  TRANSCRIBE_LIVE_MODEL;

describe("a bidiGenerateContent model that refuses AUDIO", () => {
  /** The listing order the live run saw: the transcriber first. */
  const candidates = [TRANSCRIBE_LIVE_MODEL, NATIVE_AUDIO_MODEL];

  it("RED: driving the first candidate directly is refused with the observed 1007", async () => {
    const provider = await startFakeProvider({
      audioUnsupportedModels: [TRANSCRIBE_LIVE_MODEL],
    });
    try {
      const err = await geminiLiveWS(
        { apiKey: "test-key" },
        AUDIO_PROMPT,
        undefined,
        TRANSCRIBE_LIVE_MODEL,
        { host: "localhost", port: provider.port, ca: cert, waitMs: 2000 },
      ).then(
        () => null,
        (e: unknown) => e,
      );

      expect(err).toBeInstanceOf(WSClosedError);
      const closed = err as WSClosedError;
      expect(closed.code).toBe(1007);
      // The bytes the live provider sent — not a paraphrase.
      expect(closed.reason).toBe(OBSERVED_AUDIO_1007_REASON);
    } finally {
      provider.stop();
    }
  });

  it("GREEN: driveGeminiLiveAudio advances past the refusal and completes an AUDIO turn", async () => {
    const provider = await startFakeProvider({
      audioUnsupportedModels: [TRANSCRIBE_LIVE_MODEL],
    });
    try {
      const drive = await driveGeminiLiveAudio(
        { apiKey: "test-key" },
        AUDIO_PROMPT,
        undefined,
        candidates,
        { host: "localhost", port: provider.port, ca: cert, waitMs: 2000 },
      );

      expect(drive).not.toBeNull();
      // It moved to the model that actually serves AUDIO...
      expect(drive!.model).toBe(NATIVE_AUDIO_MODEL);
      // ...and it did not swallow the refusal — the provider's own words are
      // carried out for the skip/diagnostic message.
      expect(drive!.refused).toEqual([
        { model: TRANSCRIBE_LIVE_MODEL, reason: OBSERVED_AUDIO_1007_REASON },
      ]);

      // A REAL audio turn, not merely "no throw": the leg grades on these counts.
      const turn = summarizeGeminiLiveTurn(drive!.result.rawMessages);
      expect(turn.setupCompleteCount).toBe(1);
      expect(turn.audioPartCount).toBeGreaterThan(0);
      expect(turn.textPartCount).toBe(0);
      expect(turn.turnCompleteCount).toBe(1);

      // The provider saw BOTH setups, in listing order — the advance happened on
      // the wire, not by this test agreeing with itself.
      const setupModels = provider.received
        .filter((m) => m.setup)
        .map((m) => m.setup!.model)
        .filter((m): m is string => typeof m === "string");
      expect(setupModels).toEqual(candidates);
    } finally {
      provider.stop();
    }
  });

  it("returns null — an honest skip — when EVERY candidate refuses AUDIO", async () => {
    // The listing exposes only transcribers. That is unavailability, not drift:
    // there is no model this leg can grade an AUDIO turn against.
    const provider = await startFakeProvider({ audioUnsupportedModels: candidates });
    try {
      const drive = await driveGeminiLiveAudio(
        { apiKey: "test-key" },
        AUDIO_PROMPT,
        undefined,
        candidates,
        { host: "localhost", port: provider.port, ca: cert, waitMs: 2000 },
      );
      expect(drive).toBeNull();
    } finally {
      provider.stop();
    }
  });

  it("does NOT swallow a non-modality failure — a mute provider still fails", async () => {
    // NEGATIVE CONTROL for the catch above. `driveGeminiLiveAudio` recovers from
    // exactly one condition; a helper that walked candidates on ANY error would
    // turn every real live failure into a silent `null` skip and hollow out the
    // leg. A mute provider is the failure this file already reproduces.
    const provider = await startFakeProvider({ muteAfterSetup: true });
    try {
      await expect(
        driveGeminiLiveAudio({ apiKey: "test-key" }, AUDIO_PROMPT, undefined, candidates, {
          host: "localhost",
          port: provider.port,
          ca: cert,
          waitMs: 1000,
        }),
      ).rejects.toThrow(/turn model=/);
    } finally {
      provider.stop();
    }
  });

  it("isModalityRefusal keys on the refusal sentence, never on the model name", () => {
    // Modality-agnostic by construction: the TEXT refusal at the top of this
    // file and the AUDIO refusal above are the same sentence, so one predicate
    // must recognize both.
    expect(isModalityRefusal(new WSClosedError("x", 1007, OBSERVED_1007_REASON))).toBe(true);
    expect(isModalityRefusal(new WSClosedError("x", 1007, OBSERVED_AUDIO_1007_REASON))).toBe(true);
    // A 1007 that is NOT a modality refusal is a real protocol error and must
    // propagate — the fake provider sends exactly this one for malformed JSON.
    expect(isModalityRefusal(new WSClosedError("x", 1007, "Malformed JSON"))).toBe(false);
    // Right sentence, wrong code — still not a modality refusal.
    expect(isModalityRefusal(new WSClosedError("x", 1011, OBSERVED_AUDIO_1007_REASON))).toBe(false);
    expect(isModalityRefusal(new Error(OBSERVED_AUDIO_1007_REASON))).toBe(false);
  });
});

/**
 * Red-green + guard tests for the Gemini Live probe's REQUESTED RESPONSE MODALITY.
 *
 * THE BUG. The probe opened every Live session with
 * `generationConfig.responseModalities = ["TEXT"]`. Every model exposing
 * `bidiGenerateContent` is a native-audio model that supports only `AUDIO`
 * (Google's capabilities guide: the native audio models "only support `AUDIO`
 * response modality"), so the provider REFUSED the session out-of-band with an
 * RFC 6455 CLOSE frame, recovered verbatim from a live drift run:
 *
 *   code=1007 reason="The requested combination of response modalities (TEXT) is
 *   not supported by the model. models/gemini-3.1-flash-live-preview"
 *
 * 1007 is a refusal, not a timeout — the request never had a chance of being
 * served, so the leg reported provider-refusal noise instead of drift on every
 * run.
 *
 * THE PROOF. These tests stand up a local TLS server that ENFORCES Google's
 * rule — one modality per session, `AUDIO` only — and drive the REAL exported
 * `geminiLiveWS` probe against it through the REAL `connectTLSWebSocket`
 * transport and the REAL server-side `WebSocketConnection` framing. Nothing
 * about the protocol path is reimplemented here, so:
 *
 *   RED   — with the probe requesting `["TEXT"]`, "drives a complete AUDIO turn"
 *           fails with exactly the 1007 frame above.
 *   GREEN — with the probe requesting `["AUDIO"]`, it observes a real audio
 *           event sequence: setupComplete → inlineData parts → turnComplete.
 *
 * The refusal itself is anchored to `OBSERVED_1007_REASON`, copied from the
 * drift-report artifact rather than generated by this file's expectations.
 *
 * NOT PROVEN HERE: that the live endpoint accepts `["AUDIO"]` and emits this
 * exact sequence. That is established from Google's published capabilities guide
 * and can only be confirmed by a live run with a real GOOGLE_API_KEY.
 *
 * THE SAME MIS-DRIVE, ON THE OTHER SIDE. Once the real side was asking for a
 * modality the model serves, the tool-call leg reported that the provider emits
 * `serverContent` and the mock does not — because the MOCK side was still being
 * driven by a text-shaped tool fixture into a bare `toolCall` with no model turn.
 * The final section of this file holds that down end to end, with the fake
 * provider emitting the tool turn in the order the live artifact proves it used
 * (`serverContent` strictly before `toolCall`).
 */
